package ru.vikulinva.catalogstarter.agent;

import com.fasterxml.jackson.databind.JsonNode;

/**
 * Инструмент, который агент может вызвать.
 *
 * <p>Описание — это не документация для человека, а часть подсказки: по нему
 * модель решает, звать инструмент или нет. Расплывчатое описание («работа с
 * товарами») даёт расплывчатый выбор.
 */
public interface Tool {

    /** Имя, которым модель зовёт инструмент. Короткое, без пробелов. */
    String name();

    /** Что делает и какие аргументы принимает — одной фразой, для модели. */
    String description();

    /**
     * Меняет ли инструмент данные. Читающие инструменты агент зовёт сам,
     * изменяющие — только после подтверждения человеком: у модели нет способа
     * отличить «покажи остаток» от «зарезервируй сто штук», а цена ошибки разная.
     */
    default boolean mutating() {
        return false;
    }

    /** Выполняет вызов и возвращает результат текстом — его увидит модель. */
    String run(JsonNode arguments);
}
