package ru.vikulinva.catalogstarter.assistant;

/**
 * Порт к модели эмбеддингов: текст превращается в вектор, близкие по смыслу
 * тексты дают близкие векторы.
 *
 * <p>Отдельный интерфейс — по той же причине, что и у {@code LlmClient}:
 * провайдера меняют (он платный и лимитированный), он падает, а в тестах его
 * подменяют. База знаний и помощник про это знать не должны.
 */
public interface Embeddings {

    /** Вектор фиксированной длины. Длина одна и та же для всех текстов. */
    float[] embed(String text);
}
