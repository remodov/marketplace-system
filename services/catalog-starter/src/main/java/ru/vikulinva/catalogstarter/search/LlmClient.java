package ru.vikulinva.catalogstarter.search;

/**
 * Порт к языковой модели. Отдельный интерфейс нужен не ради красоты: провайдера
 * меняют, он падает, и его надо подменять в тестах — а сервис поиска про это
 * знать не должен.
 */
public interface LlmClient {

    /** Возвращает ответ модели как есть. Бросает исключение, если провайдер недоступен. */
    String complete(String prompt);
}
