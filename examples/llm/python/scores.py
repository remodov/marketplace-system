"""Посмотреть своими глазами, какие числа даёт поиск по близости.

Запуск: python3 scores.py

Тут и видно, почему порог в assistant.MIN_SCORE стоит там, где стоит: вопросы по
делу дают заметно больше, а вопрос не по теме проваливается почти в ноль. Поменяйте
STOP в embeddings.py на пустое множество и запустите снова — вопрос про масло в
двигателе начнёт находить правила возврата.
"""
import assistant
import knowledge
import shop

ВОПРОСЫ = [
    "сколько дней на возврат товара",
    "когда вернут деньги за возврат",
    "сколько стоит доставка курьером",
    "есть ли беспроводная мышь и сколько стоит",
    "какая гарантия на электронику",
    "как поменять масло в двигателе автомобиля",
]

if __name__ == "__main__":
    base = shop.fill(knowledge.KnowledgeBase())
    print("кусков в базе: %d, порог: %.2f\n" % (base.size(), assistant.MIN_SCORE))
    for вопрос in ВОПРОСЫ:
        print(вопрос)
        for m in base.search(вопрос, 3, -1):
            мимо = " " if m.score >= assistant.MIN_SCORE else "×"
            print("  %s %.3f  %-28s %s" % (мимо, m.score, m.chunk.source, m.chunk.text[:58]))
        print()
