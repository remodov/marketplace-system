"""Порт к модели эмбеддингов и локальная замена провайдера.

Текст превращается в вектор, близкие по смыслу тексты дают близкие векторы.
Отдельная функция здесь не ради красоты: провайдера меняют (он платный и
лимитированный), он падает, а в тестах его подменяют.

Честно о границе: хэш-эмбеддинг не знает про смысл. Он сближает тексты, у
которых совпадают слова, и ничего не знает про синонимы. Настоящая модель
сближает их по смыслу. Зачем он тогда нужен: весь остальной код — нарезка,
поиск, сборка подсказки, отказ при отсутствии ответа — работает и проверяется
без ключа, интернета и денег. Подключение провайдера меняет ровно одну функцию.
"""
import math
import re

DIMENSIONS = 256

# Слова-связки выбрасываются. Без этого вопрос «как поменять масло в двигателе»
# находит правила возврата: общих «как», «в», «на» хватает, чтобы близость
# перевалила любой разумный порог, — и помощник уверенно отвечает не по делу.
STOP = {
    "как", "что", "это", "или", "для", "при", "над", "под", "без", "его", "все",
    "так", "уже", "там", "где", "они", "она", "оно", "мне", "нам", "вам", "чем",
    "если", "когда", "какой", "какая", "какие", "можно", "нужно", "есть", "быть",
}

_WORD = re.compile(r"[^\w]+", re.UNICODE)


def words(text):
    """Длинные слова обрезаются до шести букв — грубая замена морфологии.

    «Доставка» и «доставки» так попадают в одну корзину, а без этого вопрос
    покупателя не совпал бы с документом ни одним словом. На коротких словах
    приём не спасает: «товар» и «товара» так и останутся разными. Настоящей
    модели эмбеддингов такой костыль не нужен вовсе, она про падежи знает.
    """
    if not text:
        return []
    out = []
    for raw in _WORD.split(text.lower()):
        if len(raw) > 2 and raw not in STOP:
            out.append(raw[:6])
    return out


def _fnv1a(word):
    """Свой хэш, а не встроенный: у встроенного в Python результат меняется от
    запуска к запуску, и один и тот же текст давал бы разные векторы."""
    h = 0x811C9DC5
    for ch in word.encode("utf-8"):
        h = ((h ^ ch) * 0x01000193) & 0xFFFFFFFF
    return h


def embed(text):
    vector = [0.0] * DIMENSIONS
    for word in words(text):
        h = _fnv1a(word)
        # Знак от второго байта хэша: иначе все слова только прибавляют, и любые
        # два длинных текста оказываются похожими просто потому, что длинные.
        vector[h % DIMENSIONS] += 1.0 if (h >> 16) & 1 == 0 else -1.0
    return _normalize(vector)


def _normalize(vector):
    """Без нормировки длинный текст «побеждает» короткий на любом вопросе."""
    length = math.sqrt(sum(v * v for v in vector))
    if length == 0:
        return vector
    return [v / length for v in vector]
