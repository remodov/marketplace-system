/* Порт к модели эмбеддингов и локальная замена провайдера.
 *
 * Текст превращается в вектор, близкие по смыслу тексты дают близкие векторы.
 * Отдельная функция здесь не ради красоты: провайдера меняют (он платный и
 * лимитированный), он падает, а в тестах его подменяют.
 *
 * Честно о границе: это не смысловые векторы. Хэш-эмбеддинг сближает тексты, у
 * которых совпадают слова, и ничего не знает про синонимы. Настоящая модель
 * сближает их по смыслу. Зачем он тогда нужен: весь остальной код — нарезка,
 * поиск, сборка подсказки, отказ при отсутствии ответа — работает и проверяется
 * без ключа, интернета и денег. Подключение провайдера меняет ровно эту функцию. */

export const DIMENSIONS = 256

/* Слова-связки выбрасываются. Без этого вопрос «как поменять масло в двигателе»
   находит правила возврата: общих «как», «в», «на» хватает, чтобы близость
   перевалила любой разумный порог, — и помощник уверенно отвечает не по делу. */
export const STOP = new Set([
  'как', 'что', 'это', 'или', 'для', 'при', 'над', 'под', 'без', 'его', 'все',
  'так', 'уже', 'там', 'где', 'они', 'она', 'оно', 'мне', 'нам', 'вам', 'чем',
  'если', 'когда', 'какой', 'какая', 'какие', 'можно', 'нужно', 'есть', 'быть',
])

/** Длинные слова обрезаются до шести букв — грубая замена морфологии:
 *  «доставка» и «доставки» так попадают в одну корзину. На коротких словах приём
 *  не спасает: «товар» и «товара» так и останутся разными. Настоящей модели
 *  эмбеддингов такой костыль не нужен вовсе, она про падежи знает. */
export function words(text) {
  if (!text) return []
  return text.toLowerCase()
    .split(/[^\p{L}\p{N}]+/u)
    .filter(w => w.length > 2 && !STOP.has(w))
    .map(w => (w.length > 6 ? w.slice(0, 6) : w))
}

/* Свой хэш, а не какой-нибудь из библиотеки: пять строк, зато видно, что
   происходит, и результат одинаков при каждом запуске. */
function fnv1a(word) {
  let h = 0x811c9dc5
  for (const byte of new TextEncoder().encode(word)) {
    h = Math.imul(h ^ byte, 0x01000193) >>> 0
  }
  return h
}

export function embed(text) {
  const vector = new Array(DIMENSIONS).fill(0)
  for (const word of words(text)) {
    const h = fnv1a(word)
    /* Знак от второго байта хэша: иначе все слова только прибавляют, и любые два
       длинных текста оказываются похожими просто потому, что длинные. */
    vector[h % DIMENSIONS] += ((h >>> 16) & 1) === 0 ? 1 : -1
  }
  return normalize(vector)
}

/** Без нормировки длинный текст «побеждает» короткий на любом вопросе. */
function normalize(vector) {
  const length = Math.sqrt(vector.reduce((s, v) => s + v * v, 0))
  return length === 0 ? vector : vector.map(v => v / length)
}

/** Векторы нормированы, поэтому косинус — просто скалярное произведение. */
export function cosine(a, b) {
  let sum = 0
  for (let i = 0; i < Math.min(a.length, b.length); i++) sum += a[i] * b[i]
  return sum
}
