/* Ответ на вопрос покупателя по документам магазина.
 *
 * Схема целиком: вопрос → поиск похожих кусков → подсказка из найденного →
 * ответ модели. Модель тут ничего не знает про магазин и не должна знать: всё,
 * чем она располагает, лежит в подсказке. Это и есть смысл RAG — знание
 * приносят из базы, а не из весов модели.
 *
 * Главное правило, из-за которого всё и затевалось: ничего не нашли — отвечаем
 * «не знаю», а не зовём модель. Модель, которой не дали контекст, не молчит —
 * она сочиняет правдоподобный ответ про сроки возврата, и по нему покупатель
 * идёт к оператору. Отказ дешевле выдуманного ответа. */

/* Сколько кусков кладём в подсказку. Больше — дороже и хуже: лишние куски
   разбавляют нужный и уводят ответ в сторону. */
export const TOP_K = 3

/* Порог близости. Не угадан, а измерен на этих документах: вопросы по делу дают
   заметно больше, вопрос не по теме проваливается почти в ноль. Со смысловой
   моделью эмбеддингов порог подбирают заново, глядя на выдачу. */
export const MIN_SCORE = 0.15

export const PROMPT = (context, question) => `Ты помощник интернет-магазина. Ответь на вопрос покупателя, опираясь
ТОЛЬКО на фрагменты ниже. Если ответа в них нет, так и скажи — не придумывай.
Отвечай коротко, двумя-тремя предложениями.

Фрагменты:
${context}

Вопрос: ${question}
`

export class RagAssistant {
  #base
  #llm

  /** llm — функция «подсказка → ответ» или null, если провайдера нет. */
  constructor(base, llm = null) {
    this.#base = base
    this.#llm = llm
  }

  async ask(question) {
    const found = this.#base.search(question, TOP_K, MIN_SCORE)
    if (found.length === 0) {
      return {
        text: 'Не нашёл ответа в документах магазина. Спросите оператора — он посмотрит вручную.',
        sources: [],
        grounded: false,
      }
    }

    const sources = [...new Set(found.map(m => m.chunk.source))]
    const context = found.map(m => `- ${m.chunk.text}`).join('\n')

    if (!this.#llm) {
      /* Без провайдера отдаём найденное как есть. Половина пользы RAG — именно в
         поиске: человек видит нужный абзац, даже когда сформулировать ответ
         некому. */
      return { text: found[0].chunk.text, sources, grounded: true }
    }
    try {
      const text = await this.#llm(PROMPT(context, question))
      return { text: String(text).trim(), sources, grounded: true }
    } catch {
      return { text: found[0].chunk.text, sources, grounded: true }
    }
  }
}
